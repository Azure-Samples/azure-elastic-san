def list_iscsi_sessions():
    """Parse 'iscsictl -L -v' into a list of per-session field dicts (keys
    such as 'Target name', 'Target portal', 'Session state'). The nickname
    used to add a session is not part of the kernel's session state and is
    therefore not recoverable from this listing. Sessions are correlated by
    Target name only because an iSCSI TargetAddress redirect can legitimately
    change Target portal after login."""
    output = _run_command(
        ["iscsictl", "-L", "-v"], "iscsictl session listing", AZ_CLI_TIMEOUT_SECONDS
    )
    return _parse_iscsictl_verbose_sessions(output)


def _parse_iscsictl_verbose_sessions(output):
    sessions = []
    fields = {}

    def append_session():
        if not fields:
            return
        required_fields = ("Target name", "Target portal", "Session state")
        missing_fields = [field for field in required_fields if field not in fields]
        if missing_fields:
            raise ElasticSanConnectError(
                "Could not safely parse 'iscsictl -L -v': a session block is missing {}".format(
                    ", ".join(missing_fields)
                )
            )
        sessions.append(dict(fields))

    for line in output.splitlines() + [""]:
        if not line.strip():
            append_session()
            fields = {}
            continue
        if ":" not in line:
            continue
        label, _, value = line.partition(":")
        label = label.strip()
        if label == "Session ID" and fields:
            append_session()
            fields = {}
        fields[label] = value.strip()
    return sessions


def same_iqn(left, right):
    """IQNs are compared exactly but case-insensitively, never by substring."""
    return left.lower() == right.lower()


def sessions_for_target(sessions, target_name):
    return [
        session
        for session in sessions
        if same_iqn(session.get("Target name", ""), target_name)
    ]


def belongs_to_volume(target_name, volume_iqn):
    """True for the volume's own IQN or that IQN with one ':az-<zone>' suffix.

    Exact and case-insensitive (never a substring), matching the Linux and Windows
    scripts, so a volume connected in either zonal mode is recognized on every portal.
    """
    target_name, volume_iqn = target_name.lower(), volume_iqn.lower()
    if target_name == volume_iqn:
        return True
    prefix = volume_iqn + ":az-"
    zone = target_name[len(prefix):] if target_name.startswith(prefix) else ""
    return bool(zone) and ":" not in zone


def sessions_for_volume(sessions, volume_iqn):
    return [
        session
        for session in sessions
        if belongs_to_volume(session.get("Target name", ""), volume_iqn)
    ]


def session_is_connected(session):
    return (
        session.get("Session state", "").strip().lower() == "connected"
        and session.get("Enable", "Yes").strip().lower() not in ("no", "off", "disabled")
    )


def describe_session_state(session):
    return "{}{}".format(
        session.get("Session state", "<missing>"),
        " (disabled)"
        if session.get("Enable", "Yes").strip().lower() in ("no", "off", "disabled")
        else "",
    )


def add_iscsi_session(nickname, config_path):
    command = [
        "iscsictl",
        "-A",
        "-n",
        nickname,
        "-c",
        config_path,
    ]
    _run_command(
        command, "iscsictl add session '{}'".format(nickname), ISCSICTL_COMMAND_TIMEOUT_SECONDS
    )


def wait_for_connected_session(
    target_name,
    timeout=SESSION_READY_TIMEOUT_SECONDS,
    poll_interval=SESSION_POLL_INTERVAL_SECONDS,
    monotonic=None,
    sleep=None,
    expected_count=1,
):
    """Poll only *target_name* until *expected_count* connected sessions are visible."""
    monotonic = time.monotonic if monotonic is None else monotonic
    sleep = time.sleep if sleep is None else sleep
    deadline = monotonic() + timeout
    while True:
        matching_sessions = sessions_for_target(list_iscsi_sessions(), target_name)
        connected_count = len(
            [session for session in matching_sessions if session_is_connected(session)]
        )
        if connected_count >= expected_count:
            return
        now = monotonic()
        if now >= deadline:
            raise ElasticSanConnectError(
                "Timed out after {} seconds waiting for {} session(s) to target '{}' to become "
                "Connected ({} Connected). The iscsictl add requests were already submitted and "
                "may still create or leave live sessions; inspect 'iscsictl -L -v' before "
                "retrying.".format(timeout, expected_count, target_name, connected_count)
            )
        sleep(min(poll_interval, deadline - now))


