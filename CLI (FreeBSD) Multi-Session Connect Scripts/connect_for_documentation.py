def ensure_iscsid_enabled_and_running():
    returncode, current, _ = _run_subprocess(
        ["sysrc", "-n", "iscsid_enable"], "sysrc iscsid_enable query", SHORT_COMMAND_TIMEOUT_SECONDS
    )
    if returncode != 0:
        current = ""
    if current.strip().upper() != "YES":
        _run_command(
            ["sysrc", "iscsid_enable=YES"], "sysrc iscsid_enable=YES", SHORT_COMMAND_TIMEOUT_SECONDS
        )
    returncode, _, _ = _run_subprocess(
        ["service", "iscsid", "onestatus"], "service iscsid onestatus", SHORT_COMMAND_TIMEOUT_SECONDS
    )
    if returncode != 0:
        _run_command(
            ["service", "iscsid", "start"], "service iscsid start", SHORT_COMMAND_TIMEOUT_SECONDS
        )


def _query_sysrc(variable, config_file=None):
    """Return a variable's value, or None when sysrc reports it undefined (non-zero exit).

    sysrc also reads /etc/defaults/rc.conf, so a variable that has a stock
    default is never undefined; an explicitly empty value is returned as "".
    """
    command = ["sysrc"]
    if config_file is not None:
        command.extend(["-f", config_file])
    command.extend(["-n", variable])
    returncode, value, _ = _run_subprocess(
        command, "sysrc {} query".format(variable), SHORT_COMMAND_TIMEOUT_SECONDS
    )
    return value.strip() if returncode == 0 else None


def iscsictl_flags_are_stock(flags):
    # An explicitly empty value makes rc.d/iscsictl run a bare 'iscsictl', which
    # only lists sessions, so only undefined or "-Aa" re-adds them at boot.
    return flags is None or flags == STOCK_ISCSICTL_FLAGS


