def plan_volume_action(plan, managed_entries, sessions, config_path):
    """Apply the existing-state policy to one volume before anything is mutated.

    Returns None when the volume should be connected, otherwise the reason it
    is skipped. Sessions and managed entries belong to the volume when their
    target is its IQN or that IQN with one ':az-<zone>' suffix, on any portal.
    A volume is connected only when it has no session and either no managed
    entry or exactly its own planned entries (re-establishing them). Reruns
    therefore never add a second set of entries or sessions for a volume, even
    when a later run uses another layout, zonal mode or name casing.
    A volume selected more than once in the same run is planned once by
    build_connection_plan.
    """
    live_sessions = sessions_for_volume(sessions, plan.volume_iqn)
    persistent_entries = [
        entry for entry in managed_entries if belongs_to_volume(entry.target_name, plan.volume_iqn)
    ]
    if any(not session_is_connected(session) for session in live_sessions):
        return (
            "pre-existing session anomaly ({} session(s): {}); this script never adds, removes "
            "or modifies these sessions. Inspect 'iscsictl -L -v', recover them manually or run "
            "disconnect_for_documentation.py for this volume, then re-run".format(
                len(live_sessions),
                ", ".join(describe_session_state(session) for session in live_sessions),
            )
        )
    if live_sessions:
        reason = "already connected ({} live / {} persistent)".format(
            len(live_sessions), len(persistent_entries)
        )
        if not persistent_entries:
            reason += (
                "; the sessions are not persistent because {} has no managed entry for them. To "
                "make them persistent, run disconnect_for_documentation.py for this volume during "
                "a maintenance window and re-run".format(config_path)
            )
        return reason
    if not persistent_entries:
        return None

    def identities(entries):
        return sorted((entry.nickname, entry.target_name, entry.target_address) for entry in entries)

    if identities(persistent_entries) == identities(plan.entries()):
        return None
    nicknames = [entry.nickname for entry in persistent_entries]
    return (
        "persistent configuration exists but no live sessions (managed {} {}); this script "
        "will not add a second set of entries for the same volume. Establish them with "
        "'iscsictl -A -n <nickname>' for each entry, or run disconnect_for_documentation.py "
        "for this volume and re-run".format(
            "entry" if len(nicknames) == 1 else "entries",
            ", ".join("'{}'".format(nickname) for nickname in nicknames),
        )
    )


def add_sessions_for_volume(plan, config_path):
    """Add every planned session, then wait until all of them are Connected.

    The volume's sessions are listed again just before submitting, so a session
    that appeared after the pre-mutation inventory is never duplicated.
    """
    matching_sessions = sessions_for_volume(list_iscsi_sessions(), plan.volume_iqn)
    unhealthy_sessions = [
        session for session in matching_sessions if not session_is_connected(session)
    ]
    if unhealthy_sessions:
        states = sorted(set(describe_session_state(session) for session in unhealthy_sessions))
        raise ElasticSanConnectError(
            "{}: found an existing non-connected session for target '{}' (state: {}). "
            "The script will not add a duplicate or remove the stale session. Inspect "
            "'iscsictl -L -v', recover or remove that specific session manually, and retry.".format(
                plan.volume_name, plan.target_name, ", ".join(states)
            )
        )
    if matching_sessions:
        print(
            "{} [{}]: Skipped -- {} Connected session(s) already established".format(
                plan.volume_name, plan.target_name, len(matching_sessions)
            )
        )
        return

    added_addresses = set()
    for nickname, address in zip(plan.nicknames, plan.session_addresses):
        try:
            add_iscsi_session(nickname, config_path)
        except ElasticSanConnectError as error:
            if address in added_addresses:
                raise ElasticSanConnectError("{} {}".format(error, SAME_PORTAL_REJECTED_HINT))
            raise
        added_addresses.add(address)
    wait_for_connected_session(plan.target_name, expected_count=len(plan.nicknames))
    print(
        "{} [{}]: Connected {} session(s)".format(
            plan.volume_name, plan.target_name, len(plan.nicknames)
        )
    )


def execute_connection_plan(plans, config_path, number_of_sessions):
    """Run prerequisites, the pre-mutation plan and the connect phase.

    Returns the names of the volumes connected in this run; validation treats
    problems on those as failures and problems on skipped volumes as warnings.
    The caller must run check_freebsd_mutation_prerequisites() first.
    """
    if not plans:
        raise ElasticSanConnectError(
            "Refusing to execute an empty Azure Elastic SAN connection plan"
        )
    validate_session_count(number_of_sessions)
    if any(len(plan.nicknames) != number_of_sessions for plan in plans):
        raise ElasticSanConnectError(
            "Every planned volume must have exactly {} session(s)".format(number_of_sessions)
        )
    _, lock_fd = acquire_config_transaction_lock(config_path)
    try:
        existing_content_bytes, existed, original_stat = read_config_file(config_path)
        # Reject a malformed block before any host mutation.
        managed_entries = read_managed_entries(existing_content_bytes)

        ensure_freebsd_prerequisites()
        print(RECOMMENDED_SETTINGS_NOTICE)

        sessions = list_iscsi_sessions()
        plans_to_connect = []
        for plan in plans:
            skip_reason = plan_volume_action(plan, managed_entries, sessions, config_path)
            if skip_reason is None:
                plans_to_connect.append(plan)
            else:
                print("{} [{}]: Skipped: {}".format(plan.volume_name, plan.target_name, skip_reason))
        if not plans_to_connect:
            return []
        # Reject a conflicting entry before the first config write.
        compute_new_config_content(
            existing_content_bytes, render_full_managed_block(plans_to_connect)
        )

        # The on-disk backup is taken once and stays the pre-run config for manual
        # recovery; per-volume rollback uses the in-memory bytes from before that volume.
        backup_config(config_path, existing_content_bytes, existed)
        current_content, current_existed = existing_content_bytes, existed
        connected_volume_names = []
        for plan in plans_to_connect:
            # Each volume is its own config transaction, so a failure removes only
            # that volume's entries and earlier volumes keep theirs (and stay persistent).
            new_content = compute_new_config_content(
                current_content, render_full_managed_block([plan])
            )
            write_config_atomically(config_path, new_content, original_stat)
            try:
                add_sessions_for_volume(plan, config_path)
            except (ElasticSanConnectError, OSError) as error:
                restore_config_content(
                    config_path, current_content, current_existed, original_stat
                )
                earlier = ""
                if connected_volume_names:
                    earlier = (
                        " Volume(s) connected earlier in this run keep their sessions and "
                        "entries: {}.".format(
                            ", ".join("'{}'".format(name) for name in connected_volume_names)
                        )
                    )
                raise ElasticSanConnectError(
                    "Failed while establishing the iSCSI sessions for '{}'; restored {} to its "
                    "state before this volume, which removes only that volume's entries.{} This "
                    "rollback only restores the config file: iscsictl add requests may already "
                    "have created or may still create live sessions, and this script never "
                    "removes sessions. Inspect 'iscsictl -L -v' and run "
                    "disconnect_for_documentation.py for '{}' before retrying. Original "
                    "error: {}".format(
                        plan.volume_name, config_path, earlier, plan.volume_name, error
                    )
                )
            current_content, current_existed = new_content, True
            connected_volume_names.append(plan.volume_name)
        return connected_volume_names
    finally:
        release_config_transaction_lock(lock_fd)


