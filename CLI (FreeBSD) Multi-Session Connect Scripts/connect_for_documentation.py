def main(argv=None):
    parser = create_argument_parser()
    args = parser.parse_args(sys.argv[1:] if argv is None else argv)

    resource_group_name = args.resource_group
    elastic_san_name = args.elastic_san
    volume_group_name = args.volume_group
    volume_names = args.volumes
    if None in (resource_group_name, elastic_san_name, volume_group_name, volume_names):
        raise ElasticSanConnectError(
            "Need to provide resource_group_name, elastic_san_name, volume_group_name, "
            "volume_names to connect to the Elastic SAN volume(s)"
        )
    try:
        number_of_sessions = int(args.num_of_sessions)
    except (TypeError, ValueError):
        number_of_sessions = args.num_of_sessions
    validate_session_count(number_of_sessions)

    # Privilege and platform are checked before any Azure lookup so an unusable
    # host stops before doing work. --dry-run performs no native calls at all.
    if not args.dry_run:
        check_freebsd_mutation_prerequisites()

    check_az_cli_available()

    plans = build_connection_plan(
        args.elastic_san_subscription,
        resource_group_name,
        elastic_san_name,
        volume_group_name,
        volume_names,
        number_of_sessions,
        args.enable_zonal_affinity,
        args.enable_vip_distribution,
    )
    if number_of_sessions > 1:
        print(MULTIPATH_NOTICE)

    if args.dry_run:
        print("[dry-run] No mutating commands (sysrc/service/iscsictl) will be run.")
        for line in describe_plan(plans, number_of_sessions):
            print("[dry-run] " + line)
        print(
            "[dry-run] Would merge the following selected entries into the managed block in "
            "{} (existing config is not read in dry-run mode):".format(args.config_path)
        )
        print(render_full_managed_block(plans).decode("utf-8"))
        return

    connected_volume_names = execute_connection_plan(plans, args.config_path, number_of_sessions)
    # Nothing on FreeBSD needs a reboot to take effect, so there is no reboot notice.
    failed_checks = validate_connections(plans, connected_volume_names, args.config_path)
    if failed_checks:
        raise ElasticSanConnectError(
            "Validation reported {} failed check(s); review the [FAIL] lines above".format(
                failed_checks
            )
        )


if __name__ == "__main__":
    try:
        main()
    except ElasticSanConnectError as error:
        sys.stderr.write("ERROR: {}\n".format(error))
        sys.exit(1)
