# /etc/iscsi.conf atomic update with backup/rollback
# ---------------------------------------------------------------------------

def _split_managed_block(content_bytes):
    """Return (prefix, block, suffix) byte spans around any existing managed
    block in *content_bytes*, preserving everything else byte-for-byte. If no
    managed block markers are present, the whole file is treated as prefix
    (the new block is appended). Raises if exactly one marker is present,
    which indicates hand-edited/corrupted state we should not try to guess
    our way through."""
    begin_bytes = MANAGED_BLOCK_BEGIN.encode("utf-8")
    end_bytes = MANAGED_BLOCK_END.encode("utf-8")
    begin_index = content_bytes.find(begin_bytes)
    end_index = content_bytes.find(end_bytes)

    if begin_index == -1 and end_index == -1:
        return content_bytes, None, b""

    if begin_index == -1 or end_index == -1:
        raise ElasticSanConnectError(
            "{} contains only one of the managed-block BEGIN/END markers. Refusing to modify "
            "it automatically; restore the file from a backup or remove the stray marker line "
            "by hand before retrying.".format(DEFAULT_ISCSI_CONF_PATH)
        )
    if (
        (begin_index > 0 and content_bytes[begin_index - 1 : begin_index] != b"\n")
        or content_bytes[
            begin_index + len(begin_bytes) : begin_index + len(begin_bytes) + 1
        ]
        not in (b"", b"\n")
        or (end_index > 0 and content_bytes[end_index - 1 : end_index] != b"\n")
        or content_bytes[end_index + len(end_bytes) : end_index + len(end_bytes) + 1]
        not in (b"", b"\n")
    ):
        raise ElasticSanConnectError(
            "{} contains a managed-block marker that is not an exact standalone line. "
            "Refusing to modify it automatically.".format(DEFAULT_ISCSI_CONF_PATH)
        )
    if end_index < begin_index:
        raise ElasticSanConnectError(
            "{} has a managed-block END marker before its BEGIN marker. Refusing to modify it "
            "automatically.".format(DEFAULT_ISCSI_CONF_PATH)
        )

    end_line_terminator = content_bytes.find(b"\n", end_index)
    end_of_end_line = end_line_terminator + 1 if end_line_terminator != -1 else len(content_bytes)
    prefix = content_bytes[:begin_index]
    block = content_bytes[begin_index:end_of_end_line]
    suffix = content_bytes[end_of_end_line:]

    # Guard against a second, stray marker pair further down the file (e.g.
    # from a manually concatenated/restored backup). We already refuse to
    # guess our way through a single stray marker above; a duplicate pair
    # deserves the same treatment rather than being silently preserved in
    # 'suffix' forever.
    if begin_bytes in suffix or end_bytes in suffix:
        raise ElasticSanConnectError(
            "{} contains more than one managed-block marker pair. Refusing to modify it "
            "automatically; remove the duplicate BEGIN/END markers by hand before "
            "retrying.".format(DEFAULT_ISCSI_CONF_PATH)
        )

    return prefix, block, suffix


def compute_new_config_content(existing_content_bytes, managed_block_bytes):
    prefix, existing_block, suffix = _split_managed_block(existing_content_bytes)
    existing_entries = (
        parse_managed_block(existing_block) if existing_block is not None else []
    )
    selected_entries = parse_managed_block(managed_block_bytes)
    if not selected_entries:
        raise ElasticSanConnectError(
            "Refusing to write an empty Azure Elastic SAN connection plan"
        )

    merged_by_nickname = {entry.nickname: entry for entry in existing_entries}
    for entry in selected_entries:
        existing_entry = merged_by_nickname.get(entry.nickname)
        if existing_entry is not None and (
            existing_entry.target_name != entry.target_name
            or existing_entry.target_address != entry.target_address
        ):
            raise ElasticSanConnectError(
                "Generated nickname '{}' conflicts with an existing managed entry: "
                "existing target/address is '{}'/'{}', selected target/address is "
                "'{}'/'{}'. Refusing to overwrite it. Run disconnect_for_documentation.py for "
                "that volume to change its layout, then re-run.".format(
                    entry.nickname,
                    existing_entry.target_name,
                    existing_entry.target_address,
                    entry.target_name,
                    entry.target_address,
                )
            )
        merged_by_nickname[entry.nickname] = entry
    merged_block = render_managed_block(
        [merged_by_nickname[nickname] for nickname in sorted(merged_by_nickname)]
    )
    if prefix and not prefix.endswith(b"\n"):
        prefix += b"\n"
    return prefix + merged_block + suffix


def read_managed_entries(content_bytes):
    """Return the strictly parsed managed entries in *content_bytes* (possibly empty)."""
    _, block, _ = _split_managed_block(content_bytes)
    return parse_managed_block(block) if block is not None else []


def read_config_file(path):
    """Return (content_bytes, existed, stat_result_or_None)."""
    if not os.path.exists(path):
        return b"", False, None
    with open(path, "rb") as handle:
        content = handle.read()
    return content, True, os.stat(path)


def get_config_lock_path(config_path):
    """Return the stable lock inode used to serialize config transactions."""
    return os.path.join(
        os.path.dirname(os.path.abspath(config_path)), CONFIG_LOCK_FILENAME
    )


def acquire_config_transaction_lock(config_path):
    """Securely open and exclusively lock the config's separate lock file.

    The lock cannot live on iscsi.conf itself because atomic replacement changes
    that inode. The returned (path, fd) pair remains owned by the caller until
    release_config_transaction_lock() is called.
    """
    if fcntl is None:
        raise ElasticSanConnectError(
            "fcntl.flock is unavailable; config transactions require a POSIX/FreeBSD host"
        )

    lock_path = get_config_lock_path(config_path)
    flags = os.O_CREAT | os.O_RDWR
    if hasattr(os, "O_NOFOLLOW"):
        flags |= os.O_NOFOLLOW

    try:
        lock_fd = os.open(lock_path, flags, 0o600)
    except OSError as error:
        raise ElasticSanConnectError(
            "Failed to securely open config transaction lock '{}': {}".format(
                lock_path, error
            )
        )

    try:
        opened_stat = os.fstat(lock_fd)
        path_stat = os.lstat(lock_path)
        if (
            not stat.S_ISREG(opened_stat.st_mode)
            or stat.S_ISLNK(path_stat.st_mode)
            or opened_stat.st_dev != path_stat.st_dev
            or opened_stat.st_ino != path_stat.st_ino
        ):
            raise ElasticSanConnectError(
                "Config transaction lock '{}' must be a non-symlink regular file".format(
                    lock_path
                )
            )
        fcntl.flock(lock_fd, fcntl.LOCK_EX)
    except ElasticSanConnectError:
        os.close(lock_fd)
        raise
    except OSError as error:
        os.close(lock_fd)
        raise ElasticSanConnectError(
            "Failed to acquire config transaction lock '{}': {}".format(lock_path, error)
        )

    return lock_path, lock_fd


def release_config_transaction_lock(lock_fd):
    """Release and close a lock handle returned by acquire_config_transaction_lock."""
    try:
        fcntl.flock(lock_fd, fcntl.LOCK_UN)
    finally:
        os.close(lock_fd)


def backup_config(path, existing_content_bytes, existed, label="connect"):
    """Write a backup of the current config content before mutating it.
    Returns the backup path (or None if the file did not exist yet, in which
    case there is nothing to back up)."""
    if not existed:
        return None
    backup_path = "{}.bak.pre-esan-{}.{}".format(path, label, os.getpid())
    directory = os.path.dirname(path) or "."
    fd, temp_path = tempfile.mkstemp(prefix=".iscsi.conf.bak.", dir=directory)
    try:
        with os.fdopen(fd, "wb") as handle:
            handle.write(existing_content_bytes)
            handle.flush()
            os.fsync(handle.fileno())
        os.replace(temp_path, backup_path)
    except BaseException:
        if os.path.exists(temp_path):
            os.remove(temp_path)
        raise
    return backup_path


def write_config_atomically(path, new_content_bytes, original_stat):
    """Write *new_content_bytes* to *path* atomically via a temp file in the
    same directory + os.replace, preserving the original file's permissions
    and ownership where possible."""
    directory = os.path.dirname(path) or "."
    fd, temp_path = tempfile.mkstemp(prefix=".iscsi.conf.new.", dir=directory)
    try:
        with os.fdopen(fd, "wb") as handle:
            handle.write(new_content_bytes)
            handle.flush()
            os.fsync(handle.fileno())
        if original_stat is not None:
            os.chmod(temp_path, original_stat.st_mode & 0o7777)
            # Ownership preservation only applies on platforms that expose
            # os.chown (i.e. POSIX/FreeBSD, the only supported target for
            # this script) -- "where possible" per the design requirements.
            if hasattr(os, "chown"):
                try:
                    os.chown(temp_path, original_stat.st_uid, original_stat.st_gid)
                except OSError as error:
                    raise ElasticSanConnectError(
                        "Failed to preserve ownership of {} on the replacement file: {}".format(
                            path, error
                        )
                    )
        else:
            os.chmod(temp_path, 0o644)
        os.replace(temp_path, path)
    except BaseException:
        if os.path.exists(temp_path):
            os.remove(temp_path)
        raise


def restore_config_content(path, content_bytes, existed, original_stat):
    """Roll back a mutation to *content_bytes*, captured in memory before it,
    through the same atomic write (or remove the file if it did not exist
    before this run created it). *original_stat* must be the stat() of the
    file captured before this run mutated it, so its permissions and
    ownership are preserved."""
    if not existed:
        if os.path.exists(path):
            os.remove(path)
        return
    write_config_atomically(path, content_bytes, original_stat)


