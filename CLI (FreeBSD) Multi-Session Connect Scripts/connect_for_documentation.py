class ValidationReport(object):
    def __init__(self):
        self.passed = 0
        self.warnings = 0
        self.failed = 0

    def add(self, status, check, detail):
        if status == "PASS":
            self.passed += 1
        elif status == "WARN":
            self.warnings += 1
        else:
            self.failed += 1
        print("[{}] {}: {}".format(status, check, detail))


def _validate_host(report):
    iscsid_enable = _query_sysrc("iscsid_enable") or ""
    report.add(
        "PASS" if iscsid_enable.upper() == "YES" else "FAIL",
        "iscsid_enable",
        iscsid_enable or "<unset>",
    )

    iscsictl_flags = _query_sysrc("iscsictl_flags")
    iscsictl_enable = _query_sysrc("iscsictl_enable") or ""
    if not iscsictl_flags_are_stock(iscsictl_flags):
        report.add(
            "WARN",
            "iscsictl_enable",
            "{} with customized iscsictl_flags '{}', left unchanged; boot-time re-login of the "
            "managed entries is not guaranteed".format(iscsictl_enable or "<unset>", iscsictl_flags),
        )
    elif iscsictl_enable.upper() == "YES":
        report.add("PASS", "iscsictl_enable", "YES (sessions are re-added at boot)")
    else:
        report.add(
            "FAIL",
            "iscsictl_enable",
            "{} (expected YES so sessions are re-added at boot)".format(
                iscsictl_enable or "<unset>"
            ),
        )

    driver_state = get_iscsi_driver_state()
    if driver_state == "compiled-in":
        report.add("PASS", "iSCSI kernel driver", "compiled into the kernel")
    elif driver_state == "module":
        iscsi_load = _query_sysrc("iscsi_load", LOADER_CONF_PATH) or ""
        if iscsi_load.upper() == "YES":
            report.add(
                "PASS",
                "iSCSI kernel driver",
                'iscsi.ko loaded; iscsi_load="YES" in {}'.format(LOADER_CONF_PATH),
            )
        else:
            report.add(
                "FAIL",
                "iSCSI kernel driver",
                "iscsi.ko loaded but iscsi_load is {} in {}".format(
                    iscsi_load or "<unset>", LOADER_CONF_PATH
                ),
            )
    else:
        report.add(
            "FAIL", "iSCSI kernel driver", "not loaded ({} is missing)".format(ISCSI_DEVICE_NODE)
        )


def _validate_volume(report, plan, connected_this_run, sessions, managed_entries, config_path):
    """Per-volume checks against the requested session count. *sessions* /
    *managed_entries* are None when that inventory could not be read; that
    failure was already reported once."""
    prefix = "{} [{}]".format(plan.volume_name, plan.target_name)
    requested = len(plan.nicknames)
    # This script never changes a skipped volume, so its state is only a warning.
    problem = "FAIL" if connected_this_run else "WARN"

    if sessions is not None:
        matching_sessions = sessions_for_volume(sessions, plan.volume_iqn)
        connected_count = len(
            [session for session in matching_sessions if session_is_connected(session)]
        )
        not_connected = sorted(
            set(
                describe_session_state(session)
                for session in matching_sessions
                if not session_is_connected(session)
            )
        )
        if connected_count < requested:
            status = problem
        elif connected_count > requested or not_connected:
            status = "WARN"
        else:
            status = "PASS"
        detail = "{} Connected".format(connected_count)
        if status != "PASS":
            detail += ", requested {}".format(requested)
        if not_connected:
            detail += "; not Connected: {}".format(", ".join(not_connected))
        if connected_count > requested:
            detail += "; this script never removes sessions"
        report.add(status, prefix + " live sessions", detail)

        if matching_sessions:
            digests = sorted(
                set(
                    (
                        session.get("Header digest", "<missing>"),
                        session.get("Data digest", "<missing>"),
                    )
                    for session in matching_sessions
                )
            )
            if digests == [("CRC32C", "CRC32C")]:
                report.add("PASS", prefix + " digests", "header CRC32C, data CRC32C")
            else:
                report.add(
                    problem,
                    prefix + " digests",
                    "{}; expected header CRC32C, data CRC32C".format(
                        "; ".join(
                            "header {}, data {}".format(header, data) for header, data in digests
                        )
                    ),
                )

    if managed_entries is None:
        return
    entries = [
        entry for entry in managed_entries if belongs_to_volume(entry.target_name, plan.volume_iqn)
    ]
    if len(entries) == requested:
        report.add("PASS", prefix + " managed entries", str(requested))
    elif not entries:
        report.add(
            problem,
            prefix + " managed entries",
            "none in {}; the sessions are not persistent".format(config_path),
        )
    elif len(entries) < requested:
        report.add(
            problem,
            prefix + " managed entries",
            "{} in {}, requested {}; only those sessions are re-added at boot".format(
                len(entries), config_path, requested
            ),
        )
    else:
        report.add(
            "WARN",
            prefix + " managed entries",
            "{} in {}, requested {}".format(len(entries), config_path, requested),
        )


def validate_connections(plans, connected_volume_names, config_path):
    """Print read-only PASS/WARN/FAIL checks and the summary; return the FAIL count."""
    report = ValidationReport()
    _validate_host(report)
    try:
        sessions = list_iscsi_sessions()
    except ElasticSanConnectError as error:
        sessions = None
        report.add("FAIL", "iSCSI sessions", "could not list sessions: {}".format(error))
    try:
        managed_entries = read_managed_entries(read_config_file(config_path)[0])
    except (ElasticSanConnectError, OSError) as error:
        managed_entries = None
        report.add("FAIL", "managed block", "could not read {}: {}".format(config_path, error))
    for plan in plans:
        _validate_volume(
            report,
            plan,
            plan.volume_name in connected_volume_names,
            sessions,
            managed_entries,
            config_path,
        )
    print(
        "Validation: {} passed, {} warnings, {} failed".format(
            report.passed, report.warnings, report.failed
        )
    )
    return report.failed


